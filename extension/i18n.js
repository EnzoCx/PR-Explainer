function prxLang(setting) {
  if (setting === 'en' || setting === 'fr') return setting;
  return (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

function prxT(lang, key, vars = {}) {
  const value = PRX_STRINGS[lang]?.[key] ?? PRX_STRINGS.en[key] ?? key;
  return typeof value === 'string' ? value.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : value;
}
